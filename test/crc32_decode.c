/* Legacy F2 0F 38 F0/F1 encodings (CRC32) must not decode as MOVBE. */
#include "decode.h"
#include <assert.h>
#include <string.h>
static int dec(const unsigned char *b, size_t n, decoded *d) {
    unsigned char p[32] = {0}; memcpy(p, b, n); return decode(p, d);
}
int main(void) {
    decoded d;
    static const unsigned char crc[][8] = {
        {0xF2,0x0F,0x38,0xF0,0xC1}, {0xF2,0x0F,0x38,0xF1,0xC1}, {0xF2,0x0F,0x38,0xF1,0x07},
        {0xF2,0x48,0x0F,0x38,0xF1,0x07}, {0x66,0xF2,0x0F,0x38,0xF1,0x07}, {0xF2,0x66,0x0F,0x38,0xF1,0x07},
        {0x66,0xF2,0x0F,0x38,0xF1,0xC1}, {0xF2,0x41,0x0F,0x38,0xF0,0x00}, {0x67,0xF2,0x0F,0x38,0xF1,0x07},
    };
    for (size_t i = 0; i < sizeof crc / sizeof *crc; i++)
        assert(dec(crc[i], 8, &d) == 0 || d.op != BMI_MOVBE);
    /* controls: real MOVBE still decodes */
    static const unsigned char mov[][8] = {{0x0F,0x38,0xF0,0x07}, {0x0F,0x38,0xF1,0x07}, {0x66,0x0F,0x38,0xF0,0x07}, {0x48,0x0F,0x38,0xF1,0x07}};
    for (size_t i = 0; i < 4; i++) assert(dec(mov[i], 8, &d) > 0 && d.op == BMI_MOVBE);
    return 0;
}
